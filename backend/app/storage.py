"""Object storage for uploads and exports (PRD §3.1: S3-compatible in production).

`LocalObjectStore` is the local-development implementation. Keys are always generated by the
server (never from user input) and validated against path traversal. Downloads are never
authorized by key alone: every read goes through a workspace-authorized API route.
"""

import os
import re
import tempfile
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from app.config import get_settings

_KEY = re.compile(r"^[a-z0-9][a-z0-9/_.-]{0,199}$")


class ObjectStore(Protocol):
    def put(self, key: str, data: bytes) -> None: ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...


class LocalObjectStore:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        if not _KEY.match(key) or ".." in key.split("/"):
            raise ValueError("invalid object key")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise ValueError("invalid object key")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent)
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


@lru_cache
def get_object_store() -> ObjectStore:
    return LocalObjectStore(get_settings().object_store_dir)
