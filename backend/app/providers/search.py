"""Search provider interface and the deterministic fake used by tests and CI."""

import hashlib
import re
from dataclasses import dataclass
from typing import Protocol


@dataclass(frozen=True)
class SearchHit:
    url: str
    title: str
    snippet: str
    published_on: str | None = None
    # Present when the provider already returns page text (fake, offline corpus). Otherwise
    # the safe fetcher retrieves it. Snippets alone are never stored as evidence (FR-05).
    content: str | None = None


class SearchProvider(Protocol):
    name: str

    def search(
        self,
        query: str,
        *,
        max_results: int,
        allowed_domains: list[str],
        blocked_domains: list[str],
    ) -> list[SearchHit]: ...


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60] or "q"


class FakeSearch:
    """Deterministic synthetic results. No network access."""

    name = "fake"

    def search(
        self,
        query: str,
        *,
        max_results: int,
        allowed_domains: list[str],
        blocked_domains: list[str],
    ) -> list[SearchHit]:
        digest = hashlib.sha256(query.encode()).hexdigest()[:8]
        hits = []
        for n in (1, 2):
            url = f"https://docs.example.test/{_slug(query)}/{n}"
            hits.append(
                SearchHit(
                    url=url,
                    title=f"Synthetic source {n} for: {query[:80]}",
                    snippet=f"Synthetic snippet {n}",
                    published_on="2026-01-15",
                    content=(
                        f"Synthetic documentation page {n} ({digest}). It discusses: {query}. "
                        f"This text is generated by the fake search provider for testing and "
                        f"contains no real-world facts."
                    ),
                )
            )
        return hits[:max_results]
