"""Search provider interface and the deterministic fake used by tests and CI."""

import hashlib
import re
import uuid
from dataclasses import dataclass, field
from typing import Literal, Protocol


@dataclass(frozen=True)
class SearchHit:
    url: str | None
    title: str
    snippet: str
    published_on: str | None = None
    # Present when the provider already holds the document text (fake, offline corpus,
    # uploads). Otherwise the safe fetcher retrieves the page. Snippets are never stored as
    # evidence on their own (FR-05).
    content: str | None = None
    kind: Literal["web", "corpus", "upload"] = "web"
    upload_id: uuid.UUID | None = None
    locator: str | None = None


@dataclass(frozen=True)
class SearchResponse:
    hits: list[SearchHit]
    credits: float = 0.0  # provider billing units consumed, for the cost ledger
    request_id: str | None = None
    extra: dict[str, str] = field(default_factory=dict)


class SearchProvider(Protocol):
    name: str

    def search(
        self,
        query: str,
        *,
        max_results: int,
        allowed_domains: list[str],
        blocked_domains: list[str],
    ) -> SearchResponse: ...


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60] or "q"


class FakeSearch:
    """Deterministic synthetic results. No network access."""

    name = "fake"

    def search(
        self,
        query: str,
        *,
        max_results: int,
        allowed_domains: list[str],
        blocked_domains: list[str],
    ) -> SearchResponse:
        digest = hashlib.sha256(query.encode()).hexdigest()[:8]
        hits = [
            SearchHit(
                url=f"https://docs.example.test/{slug(query)}/{n}",
                title=f"Synthetic source {n} for: {query[:80]}",
                snippet=f"Synthetic snippet {n}",
                published_on="2026-01-15",
                content=(
                    f"Synthetic documentation page {n} ({digest}). It discusses: {query}. "
                    "This text is generated by the fake search provider for testing and "
                    "contains no real-world facts."
                ),
            )
            for n in (1, 2)
        ]
        return SearchResponse(hits[:max_results], credits=0.0)
